#!/usr/bin/env python3
"""Write a C header with selected symbols from a sjasmplus --sym file.

Usage: symsh.py turboace.sym NAME... > syms.h
"""
import re
import sys

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r'\s*([A-Za-z_][\w.]*)\s*:?\s*(?:EQU|equ)\s+(?:0x|\$)?([0-9A-Fa-f]+)', line)
    if m:
        syms[m.group(1)] = int(m.group(2), 16)
print('/* generated by symsh.py from %s */' % sys.argv[1])
for name in sys.argv[2:]:
    if name not in syms:
        sys.exit('symsh.py: symbol %s not found' % name)
    print('#define %-12s 0x%04X' % (name, syms[name] & 0xFFFF))
