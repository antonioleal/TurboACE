#!/usr/bin/env python3
"""Walk the stock Jupiter Ace ROM dictionary and print sjasmplus equates.

Usage: acedict.py ace.rom > rom/ace_words.inc

Header format (verified on the stock ROM): name (last char has bit 7 set),
link field (2 bytes, points to the previous word's name-length field),
name-length field (1 byte), code field (2 bytes). The FORTH vocabulary link
(RAM $3C47, copied from ROM) holds $1FFF, an empty header whose link is $1D58.
"""
import hashlib
import sys

SHA1 = '597ba8a15a292688333c84dc9fd35172abe5e7e6'

rom = open(sys.argv[1], 'rb').read()
if hashlib.sha1(rom).hexdigest() != SHA1:
    sys.exit('acedict: ROM image does not match the stock Ace ROM SHA-1')

def label(name):
    special = {'+': 'PLUS', '-': 'MINUS', '*': 'STAR', '/': 'SLASH', '.': 'DOT',
               '!': 'STORE', '@': 'FETCH', '=': 'EQ', '<': 'LT', '>': 'GT',
               '0': 'ZERO', '1': 'ONE', '2': 'TWO', ':': 'COLON', ';': 'SEMI',
               ',': 'COMMA', '"': 'QUOTE', "'": 'TICK', '(': 'LPAREN',
               ')': 'RPAREN', '[': 'LBRACK', ']': 'RBRACK', '#': 'SHARP',
               '?': 'QUERY', '\\': 'BSLASH', ' ': '_'}
    out = ''.join(c if c.isalnum() else '_' + special.get(c, f'{ord(c):02X}') + '_'
                  for c in name)
    return out.replace('__', '_').strip('_')

nlf = 0x1D58
words = []
while nlf:
    ln = rom[nlf] & 0x3F
    link = rom[nlf - 2] | rom[nlf - 1] << 8
    raw = rom[nlf - 2 - ln:nlf - 2]
    name = bytes(c & 0x7F for c in raw).decode('ascii')
    if not raw or not raw[-1] & 0x80 or any(c & 0x80 for c in raw[:-1]):
        sys.exit(f'acedict: bad header at {nlf:04X}')
    cfa = nlf + 1
    words.append((name, nlf, cfa, rom[nlf]))
    nlf = link

seen = {}
print('; Generated by tools/misc/acedict.py from the stock Ace ROM (SHA-1 %s).' % SHA1)
print('; Do not edit. ACE_NLF_x = name-length field, ACE_x = code field address')
print('; (the address compiled into colon definitions).')
for name, nlf, cfa, nl in reversed(words):
    base = 'ACE_' + label(name)
    if base in seen:
        seen[base] += 1
        base += f'_{seen[base]}'
    else:
        seen[base] = 1
    flags = ' immediate' if nl & 0x40 else ''
    print(f'{base:<18} EQU ${cfa:04X}   ; {name}{flags}')
    print(f'{"ACE_NLF_" + base[4:]:<18} EQU ${nlf:04X}')
print(f'; {len(words)} words; last ROM word UFLOAT, NLF $1D58')
